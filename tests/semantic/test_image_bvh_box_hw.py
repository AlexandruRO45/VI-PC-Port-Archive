def f2u(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def h2u(x):
    return struct.unpack("<H", struct.pack("<e", x))[0]


_SPV = {}


def shader(kind, ray):
    key = (kind, ray)
    if key not in _SPV:
        o, d = RAYS[ray]
        inv = [INF if c == 0 else 1.0 / c for c in d]
        words = [f2u(EXTENT), *[f2u(c) for c in o], *[f2u(c) for c in d], *[f2u(c) for c in inv]]
        lines = [f"v_mov_b32_e32 v1, 0x{5 if kind == 'box32' else 4:x}", "v_mov_b32_e32 v2, 0"]
        lines += [f"v_mov_b32_e32 v{3 + i}, 0x{w:x}" for i, w in enumerate(words)]
        lines += ["s_mov_b32 s4, 0x10", "s_mov_b32 s5, 0x80000000", "s_mov_b32 s6, -1", "s_mov_b32 s7, 0x81000000",
                  "image_bvh64_intersect_ray v[20:23], [v1, v2, v3, v4, v5, v6, v7, v8, v9, v10, v11, v12], s[4:7]",
                  "exp mrt0 v20, v21, v22, v23 done vm", "s_endpgm"]
        _SPV[key] = translate_lines(f"ps_bvh_box_hw_{kind}_{ray}", lines)
    return _SPV[key]


def node(kind, children, boxes):
    words = list(children)
    for b in boxes:
        if kind == 'box32':
            words += [f2u(c) for c in b]
        else:
            h = [h2u(c) for c in b]
            words += [h[0] | h[1] << 16, h[2] | h[3] << 16, h[4] | h[5] << 16]
    return {NODE + 4 * i: w for i, w in enumerate(words)}


