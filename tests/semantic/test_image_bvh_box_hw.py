_SPV_RAW = {}


def raw_shader(ntype, ray, w3=0x81000000):
    key = (ntype, tuple(ray), w3)
    if key not in _SPV_RAW:
        lines = [f"v_mov_b32_e32 v2, 0x{ntype:x}"]
        lines += [f"v_mov_b32_e32 v{3 + i}, 0x{w:x}" for i, w in enumerate(ray)]
        lines += ["s_mov_b32 s4, 0x10", "s_mov_b32 s5, 0x80000000", "s_mov_b32 s6, -1", f"s_mov_b32 s7, 0x{w3:x}",
                  "image_bvh_intersect_ray v[20:23], [" + ", ".join(f"v{r}" for r in range(2, 13)) + "], s[4:7]",
                  "exp mrt0 v20, v21, v22, v23 done vm", "s_endpgm"]
        _SPV_RAW[key] = translate_lines(f"ps_bvh_box_hw_rx6800_{len(_SPV_RAW)}", lines)
    return _SPV_RAW[key]


def raw_node(words):
    return {NODE + 4 * i: w for i, w in enumerate(words)}


def _inclusive_extent():
    """Whether this translator keeps a child whose max(tnear, 0) equals the extent (measured: yes)."""
    ray = [f2u(x) for x in (2.0, 0.25, 0.25, 0.0, 0.0, 0.0, 1.0, INF, INF, 1.0)]
    words = [0x40, MISS, MISS, MISS] + [f2u(x) for x in (-1.0, -1.0, 2.0, 1.0, 1.0, 4.0)] + [0] * 22
    return list(mrt0_words(raw_shader(5, ray), memory=raw_node(words)))[0] == 0x40


class MeasuredRoundingRX6800(unittest.TestCase):
    def test_slab_distances_round_toward_zero(self):
        inclusive = _inclusive_extent()
        for label, ntype, words, ray, want, needs_extent in RX6800_ROUNDING:
            if needs_extent and not inclusive:
                continue
            with self.subTest(label):
                self.assertEqual(list(mrt0_words(raw_shader(ntype, ray), memory=raw_node(words))), want)

    @unittest.skipIf(not _inclusive_extent(), "needs the measured extent compare max(tnear, 0) <= extent")
    def test_rows_on_the_extent_boundary(self):
        rows = [r for r in RX6800_ROUNDING if r[5]]
        self.assertEqual(len(rows), 6)
        for label, ntype, words, ray, want, _ in rows:
            with self.subTest(label):
                self.assertEqual(list(mrt0_words(raw_shader(ntype, ray), memory=raw_node(words))), want)

    def test_descriptor_size_and_big_page_do_not_change_the_words(self):
        # On the RX 6800, w3 = 0x810003FF (size all ones), 0x89000000 (big_page) and 0x890003FF (both, the value
        # the game uses) returned the same words as 0x81000000 for every case of replay_packed0/1, tri_g2a and
        # tri_g3b (8 runs, 82 distinct cases, both forms where they ran, every read-back word compared).
        label, ntype, words, ray, want, _ = RX6800_ROUNDING[0]
        for w3 in (0x810003FF, 0x89000000, 0x890003FF):
            with self.subTest(w3=hex(w3)):
                self.assertEqual(list(mrt0_words(raw_shader(ntype, ray, w3), memory=raw_node(words))), want)

