def bits(lines):
    """The word v3 holds after the lines, from a translated pixel shader run on the CPU."""
    prog = ["v_mov_b32 v3, 0"] + lines + ["exp mrt0 v3, v3, v3, v3 done vm", "s_endpgm"]
    return support.mrt0_words(support.translate_lines("ps_cmp_f64_gfx1036", prog))[0]


def set_pair(reg, value):
    return [f"v_mov_b32 v{reg}, {value[0]:#010x}", f"v_mov_b32 v{reg + 1}, {value[1]:#010x}"]


def collect(compare, k):
    """Bit k of v3 = the lane-0 result the compare left in s20."""
    return [compare, "v_cndmask_b32_e64 v6, 0, 1, s20", f"v_lshlrev_b32 v6, {k}, v6", "v_or_b32 v3, v3, v6"]


def as_bits(word, n):
    return "".join(str(word >> k & 1) for k in range(n))


class CmpF64Gfx1036(unittest.TestCase):
    def test_all_predicates_on_the_grid(self):
        for p in PREDS:
            for i, row in enumerate(CMP[p]):
                lines = set_pair(1, VALUES[i])
                for j, value in enumerate(VALUES):
                    lines += set_pair(4, value) + collect(f"v_cmp_{p}_f64_e64 s20, v[1:2], v[4:5]", j)
                with self.subTest(pred=p, a=i):
                    self.assertEqual(as_bits(bits(lines), len(VALUES)), row)

    def test_cmpx_narrows_exec_like_cmp(self):
        for p in PREDS:
            for row, i in zip(CMPX[p], CMPX_I):
                lines = set_pair(1, VALUES[i])
                for k, j in enumerate(CMPX_J):
                    lines += set_pair(4, VALUES[j]) + [
                        "s_mov_b32 s21, exec_lo", "v_mov_b32 v6, 0", f"v_cmpx_{p}_f64_e64 v[1:2], v[4:5]",
                        f"v_mov_b32 v6, {1 << k}", "s_mov_b32 exec_lo, s21", "v_or_b32 v3, v3, v6"]
                    self.assertEqual(row[k], CMP[p][i][j], (p, i, j))
                with self.subTest(pred=p, a=i):
                    self.assertEqual(as_bits(bits(lines), len(CMPX_J)), row)

    def test_source_modifiers_and_constants(self):
        for p, rows in MODS.items():
            for a, b, row in rows:
                lines = set_pair(4, B)
                for i, value in enumerate(VALUES):
                    lines += set_pair(1, value) + collect(f"v_cmp_{p}_f64_e64 s20, {a}, {b}", i)
                with self.subTest(pred=p, a=a, b=b):
                    self.assertEqual(as_bits(bits(lines), len(VALUES)), row)

    def test_cmp_class_f16_source_modifiers(self):
        for mod, rows in CLASS16.items():
            for value, row in zip(VALUE16, rows):
                lines = [f"v_mov_b32 v1, {0x3C000000 | value:#010x}"]
                for k in range(10):
                    lines += [f"v_mov_b32 v4, {1 << k:#x}"] + collect(
                        f"v_cmp_class_f16_e64 s20, {mod.format('v1')}, v4", k)
                with self.subTest(mod=mod, value=hex(value)):
                    self.assertEqual(as_bits(bits(lines), 10), row)


