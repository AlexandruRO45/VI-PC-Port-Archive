@dataclass(frozen=True)
class MadU64StatusFlags:
    """Architectural condition codes and status flags for v_mad_u64_u32."""
    zero: bool
    sign: bool
    carry_out: bool
    overflow_s64: bool
    prod_overflow_u32: bool
    s0_zero: bool
    s1_zero: bool
    s2_zero: bool

    @classmethod
    def from_mad_u64(cls, s0: int, s1: int, s2: int) -> MadU64StatusFlags:
        s0_u32 = s0 & MASK32
        s1_u32 = s1 & MASK32
        s2_u64 = s2 & MASK64

        dst_u64, carry = ref_mad_u64_u32(s0, s1, s2)
        _, overflow_s = ref_mad_i64_i32(s0, s1, s2)
        prod = ref_mul_u32_full(s0, s1)

        return cls(
            zero=(dst_u64 == 0),
            sign=bool(dst_u64 & SIGN_BIT_64),
            carry_out=bool(carry),
            overflow_s64=bool(overflow_s),
            prod_overflow_u32=(prod >= MODULO_32),
            s0_zero=(s0_u32 == 0),
            s1_zero=(s1_u32 == 0),
            s2_zero=(s2_u64 == 0),
        )


class TestValuMadU64U32Oracle(unittest.TestCase):
    """Unit tests for the reference mathematical oracle and architectural model."""

    def test_multiplication_commutativity(self) -> None:
        pairs = [
            (0, 0),
            (1, 42),
            (0x1234_5678, 0x9ABC_DEF0),
            (MASK32, 1),
            (MASK32, MASK32),
            (0x8000_0000, 2),
            (0x7FFF_FFFF, 0xFFFF_0001),
        ]
        s2 = 0xCAFE_BABE_DEAD_BEEF
        for a, b in pairs:
            res_ab = ref_mad_u64_u32(a, b, s2)
            res_ba = ref_mad_u64_u32(b, a, s2)
            self.assertEqual(res_ab, res_ba, f"Commutativity failed for ({hex(a)}, {hex(b)})")

    def test_multiplicative_zero_identity(self) -> None:
        for s2 in [0, 1, MASK32, MASK64, 0x1234_5678_9ABC_DEF0]:
            # When s0 == 0, prod is 0, dst == s2, carry == 0
            self.assertEqual(ref_mad_u64_u32(0, 0x1234_5678, s2), (s2 & MASK64, 0))
            # When s1 == 0, prod is 0, dst == s2, carry == 0
            self.assertEqual(ref_mad_u64_u32(0x9999_8888, 0, s2), (s2 & MASK64, 0))
            # Both zero
            self.assertEqual(ref_mad_u64_u32(0, 0, s2), (s2 & MASK64, 0))

    def test_multiplicative_one_identity(self) -> None:
        test_values = [0, 1, 0x5555_AAAA, MASK32]
        s2_values = [0, 100, MASK64 - 10, MASK64]
        for s1 in test_values:
            for s2 in s2_values:
                expected_sum = (s1 & MASK32) + (s2 & MASK64)
                expected_dst = expected_sum & MASK64
                expected_carry = 1 if expected_sum >= MODULO_64 else 0
                self.assertEqual(ref_mad_u64_u32(1, s1, s2), (expected_dst, expected_carry))
                self.assertEqual(ref_mad_u64_u32(s1, 1, s2), (expected_dst, expected_carry))

    def test_additive_zero_identity(self) -> None:
        test_pairs = [
            (0, 0),
            (10, 20),
            (0x10000, 0x10000),
            (MASK32, 1),
            (MASK32, MASK32),
        ]
        for s0, s1 in test_pairs:
            expected_prod = (s0 & MASK32) * (s1 & MASK32)
            # When s2 == 0, carry is strictly 0 because max 32x32 product < 2^64
            self.assertEqual(ref_mad_u64_u32(s0, s1, 0), (expected_prod, 0))
            self.assertEqual(ref_mad_nc_u64_u32(s0, s1, 0), expected_prod)

    def test_max_product_without_carry(self) -> None:
        # 0xFFFFFFFF * 0xFFFFFFFF = 0xFFFFFFFE_00000001
        expected_prod = 0xFFFF_FFFE_0000_0001
        self.assertEqual(ref_mul_u32_full(MASK32, MASK32), expected_prod)
        dst, carry = ref_mad_u64_u32(MASK32, MASK32, 0)
        self.assertEqual(dst, expected_prod)
        self.assertEqual(carry, 0)

    def test_exact_carry_generation_boundary(self) -> None:
        # We need prod + s2 to land exactly on 2^64 - 1 and 2^64
        # Case A: s0 = 2, s1 = 0x8000_0000 -> prod = 0x1_0000_0000
        # s2 = 0xFFFF_FFFF_0000_0000 - 1 = 0xFFFF_FFFE_FFFF_FFFF
        # sum = 0x1_0000_0000 + 0xFFFF_FFFE_FFFF_FFFF = 0xFFFF_FFFF_FFFF_FFFF (carry = 0)
        s0 = 2
        s1 = 0x8000_0000
        s2_a = 0xFFFF_FFFE_FFFF_FFFF
        dst_a, carry_a = ref_mad_u64_u32(s0, s1, s2_a)
        self.assertEqual(dst_a, MASK64)
        self.assertEqual(carry_a, 0)

        # Case B: prod + s2 == 2^64 (wraparound to 0, carry = 1)
        s2_b = 0xFFFF_FFFE_FFFF_FFFF + 1  # 0xFFFF_FFFF_0000_0000
        dst_b, carry_b = ref_mad_u64_u32(s0, s1, s2_b)
        self.assertEqual(dst_b, 0)
        self.assertEqual(carry_b, 1)

        # Case C: prod + s2 == 2^64 + 1
        s2_c = 0xFFFF_FFFF_0000_0001
        dst_c, carry_c = ref_mad_u64_u32(s0, s1, s2_c)
        self.assertEqual(dst_c, 1)
        self.assertEqual(carry_c, 1)

    def test_max_saturation_extremes(self) -> None:
        # s0 = MASK32, s1 = MASK32, s2 = MASK64
        # prod = 0xFFFFFFFE_00000001
        # full_sum = 0xFFFFFFFE_00000001 + 0xFFFFFFFFFFFFFFFF
        #          = 0x1_FFFFFFFE_00000000
        # dst = 0xFFFFFFFE_00000000, carry = 1
        dst, carry = ref_mad_u64_u32(MASK32, MASK32, MASK64)
        self.assertEqual(dst, 0xFFFF_FFFE_0000_0000)
        self.assertEqual(carry, 1)

        lo, hi, split_carry = ref_mad_u64_u32_split(MASK32, MASK32, MASK64)
        self.assertEqual(lo, 0x0000_0000)
        self.assertEqual(hi, 0xFFFF_FFFE)
        self.assertEqual(split_carry, 1)

    def test_split_words_consistency(self) -> None:
        test_triplets = [
            (0x1234, 0x5678, 0x9ABC),
            (0xFFFF_0000, 0x0000_FFFF, 0x1111_2222_3333_4444),
            (0x8000_0000, 0x8000_0000, 0x8000_0000_0000_0000),
            (MASK32, MASK32, MASK64),
        ]
        for s0, s1, s2 in test_triplets:
            full_dst, full_carry = ref_mad_u64_u32(s0, s1, s2)
            lo, hi, split_carry = ref_mad_u64_u32_split(s0, s1, s2)
            self.assertEqual(full_carry, split_carry)
            self.assertEqual(pack_u64(lo, hi), full_dst)
            self.assertEqual(lo, full_dst & MASK32)
            self.assertEqual(hi, (full_dst >> 32) & MASK32)

    def test_bigint_multiword_multiplication_synthesis(self) -> None:
        # Synthesize a 64-bit x 64-bit -> 128-bit multiplication using v_mad_u64_u32 limbs:
        # A = (A_hi << 32) | A_lo
        # B = (B_hi << 32) | B_lo
        # A * B = (A_lo * B_lo) + ((A_lo * B_hi + A_hi * B_lo) << 32) + ((A_hi * B_hi) << 64)
        a_64 = 0xFEDC_BA98_7654_3210
        b_64 = 0x1234_5678_9ABC_DEF1
        expected_128 = a_64 * b_64

        a_lo, a_hi = split_u64(a_64)
        b_lo, b_hi = split_u64(b_64)

        # Limb 0: A_lo * B_lo + 0
        term0_lo64, _ = ref_mad_u64_u32(a_lo, b_lo, 0)
        c0, c0_hi = split_u64(term0_lo64)

        # Limb 1: A_lo * B_hi + c0_hi
        term1_lo64, _ = ref_mad_u64_u32(a_lo, b_hi, c0_hi)

        # Limb 2: A_hi * B_lo + term1_lo64 (can carry!)
        term2_lo64, carry2 = ref_mad_u64_u32(a_hi, b_lo, term1_lo64)
        c1, c1_hi = split_u64(term2_lo64)

        # Limb 3: A_hi * B_hi + c1_hi + (carry2 << 32)
        acc3 = c1_hi + (carry2 << 32)
        term3_lo64, _ = ref_mad_u64_u32(a_hi, b_hi, acc3)

        reconstructed_128 = c0 | (c1 << 32) | (term3_lo64 << 64)
        self.assertEqual(reconstructed_128, expected_128)

    def test_signed_vs_unsigned_distinction(self) -> None:
        # s0 = 0xFFFFFFFF (-1 in signed, 4294967295 in unsigned)
        # s1 = 0xFFFFFFFF (-1 in signed, 4294967295 in unsigned)
        # s2 = 0
        # Signed: (-1) * (-1) + 0 = 1
        # Unsigned: 4294967295 * 4294967295 = 0xFFFFFFFE_00000001
        dst_u, carry_u = ref_mad_u64_u32(MASK32, MASK32, 0)
        dst_s, overflow_s = ref_mad_i64_i32(MASK32, MASK32, 0)
        self.assertEqual(dst_u, 0xFFFF_FFFE_0000_0001)
        self.assertEqual(carry_u, 0)
        self.assertEqual(dst_s, 1)
        self.assertEqual(overflow_s, 0)


