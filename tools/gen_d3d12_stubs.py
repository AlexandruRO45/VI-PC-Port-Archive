"""Generate logging stubs for D3D12 and DXGI COM interfaces from the Windows SDK headers.

For each requested interface, writes a class `<Interface>Stubs` deriving from it that overrides every method of
its chain (except IUnknown's) with a body that reports the call once through rt::d3d12::stub() and returns
E_NOTIMPL, nothing or a value-initialised result. The runtime's COM objects derive from these and override the
methods they implement, so their vtables have exactly the SDK's method order and the compiler rejects a missing
method. Run at build time (runtime/CMakeLists.txt); the output is not checked in.

    python -I tools/gen_d3d12_stubs.py --out <file> [--header <h> ...] Interface [Interface ...]

--header may repeat, so an interface chain can span headers (dxgi.h, dxgi1_2.h, ... for IDXGISwapChain3). A
header given as a bare name, or no --header at all (d3d12.h), is looked up in the directories of the INCLUDE
environment variable (set by vcvars). The output includes each header by name.
"""
import argparse
import os
import re
import sys

INTERFACE = re.compile(
    r'MIDL_INTERFACE\("[0-9a-fA-F-]+"\)\s*\n\s*(\w+)\s*:\s*public\s+(\w+)\s*\{\s*public:(.*?)\n\s*\};', re.S)
METHOD = re.compile(r'virtual\s+(.*?)\s*STDMETHODCALLTYPE\s+(\w+)\s*\((.*)\)\s*(const)?\s*=\s*0\s*;\s*$', re.S)


def find_header(name="d3d12.h"):
    """A path is used as given; a bare name is looked up in the INCLUDE directories (None when absent)."""
    if os.path.dirname(name) or os.path.isabs(name):
        return name if os.path.isfile(name) else None
    for directory in os.environ.get("INCLUDE", "").split(os.pathsep):
        path = os.path.join(directory, name)
        if directory and os.path.isfile(path):
            return path
    return None


def parse_interfaces(text):
    """name -> (base, [lines]) where a line is ('#', text) or ('m', return, name, params, const)."""
    out = {}
    for match in INTERFACE.finditer(text):
        name, base, body = match.groups()
        body = re.sub(r"/\*.*?\*/", " ", body, flags=re.S)
        items, pending = [], []
        for line in body.splitlines():
            stripped = line.strip()
            if not stripped:
                continue
            if stripped.startswith("#") and not pending:
                items.append(("#", stripped))
                continue
            pending.append(stripped)
            if re.search(r"=\s*0\s*;\s*$", stripped):
                declaration = " ".join(pending)
                pending = []
                method = METHOD.match(declaration)
                if not method:
                    raise SystemExit(f"{name}: cannot parse {declaration!r}")
                ret, method_name, params, const = method.groups()
                items.append(("m", " ".join(ret.split()), method_name, " ".join(params.split()), const or ""))
        if pending:
            raise SystemExit(f"{name}: unterminated declaration {' '.join(pending)!r}")
        out[name] = (base, items)
    return out


def chain(interfaces, leaf, sources="d3d12.h"):
    names = []
    name = leaf
    while name != "IUnknown":
        if name not in interfaces:
            raise SystemExit(f"interface {name} not found in {sources}")
        names.append(name)
        name = interfaces[name][0]
    return list(reversed(names))


def emit_class(interfaces, leaf, sources="d3d12.h"):
    lines = [f"class {leaf}Stubs : public {leaf} {{", "public:"]
    for name in chain(interfaces, leaf, sources):
        lines.append(f"    // {name}")
        for item in interfaces[name][1]:
            if item[0] == "#":
                lines.append(item[1])
                continue
            _, ret, method, params, const = item
            if ret == "void":
                result = ""
            elif ret == "HRESULT":
                result = " return E_NOTIMPL;"
            else:
                result = " return {};"
            signature = f"{ret} STDMETHODCALLTYPE {method}({params}){' const' if const else ''}"
            lines.append(f'    {signature} override {{ ::rt::d3d12::stub("{name}::{method}");{result} }}')
    lines.append("};")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--header", action="append")
    parser.add_argument("interfaces", nargs="+")
    args = parser.parse_args()
    interfaces, names = {}, []
    for requested in args.header or ["d3d12.h"]:
        header = find_header(requested)
        if not header:
            raise SystemExit(f"{requested} not found: pass a path or run from a vcvars environment")
        with open(header, encoding="utf-8", errors="replace") as f:
            interfaces.update(parse_interfaces(f.read()))
        names.append(os.path.basename(header))
    sources = ", ".join(names)

    parts = [
        "// Generated by tools/gen_d3d12_stubs.py from " + sources + ". Do not edit.",
        "#pragma once",
        *[f"#include <{name}>" for name in names],
        "namespace rt::d3d12 { void stub(const char* method); }",
        "#pragma warning(push)",
        "#pragma warning(disable : 4100)  // unreferenced parameters",
    ]
    parts += [emit_class(interfaces, leaf, sources) for leaf in args.interfaces]
    parts.append("#pragma warning(pop)")
    text = "\n".join(parts) + "\n"

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    try:
        with open(args.out, encoding="utf-8") as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
